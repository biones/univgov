export async function onRequest(context) {
  const { request, env } = context;

  if (request.method === "OPTIONS") {
    return new Response(null, {
      headers: {
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "POST, OPTIONS",
        "Access-Control-Allow-Headers": "Content-Type",
      },
    });
  }

  if (request.method !== "POST") {
    return new Response(JSON.stringify({ error: "Method Not Allowed" }), {
      status: 405,
      headers: { "Content-Type": "application/json" },
    });
  }

  try {
    let body;
    const contentType = request.headers.get("content-type") || "";
    if (contentType.includes("application/json")) {
      body = await request.json();
    } else {
      const text = await request.text();
      body = JSON.parse(text || "{}");
    }

    const pageviewId = parseInt(body.pageview_id, 10);
    const duration = Math.min(Math.max(parseInt(body.duration_seconds, 10) || 0, 0), 7200); // max 2 hours

    if (pageviewId && env.DB) {
      const now = new Date().toISOString();
      await env.DB.prepare(
        "UPDATE pageviews SET duration_seconds = MAX(duration_seconds, ?), updated_at = ? WHERE id = ?"
      ).bind(duration, now, pageviewId).run();
    }

    return new Response(JSON.stringify({ success: true }), {
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      },
    });
  } catch (err) {
    return new Response(JSON.stringify({ error: err.message }), {
      status: 500,
      headers: { "Content-Type": "application/json" },
    });
  }
}
